"""Write a generated pytest suite that carries out a zoo plan.

Each test fails exactly when the plan says so, raising its cause's planted exception type and
message. The generated conftest applies the run's test order. A run is selected with the ZOO_RUN
environment variable, and ZOO_MANIFEST can point at a manifest other than the one beside it.
"""

from collections.abc import Callable
from pathlib import Path

from benchmarks.zoo.configs import CONTROL_FAILURES, CONTROL_MODULE, CONTROL_PASSES, LAYOUT
from benchmarks.zoo.plan import Plan, manifest_json

PYTEST_INI = """\
[pytest]
# Generated by benchmarks.zoo. Keeps runs independent of caches and order-changing plugins.
addopts = -p no:cacheprovider -p no:randomly
junit_family = xunit2
"""

CONFTEST = '''\
"""Generated by benchmarks.zoo. Applies one run of the ground-truth plan in manifest.json."""

import json
import os
from pathlib import Path

import pytest

_MANIFEST_PATH = Path(os.environ.get("ZOO_MANIFEST") or Path(__file__).with_name("manifest.json"))
_MANIFEST = json.loads(_MANIFEST_PATH.read_text(encoding="utf-8"))
RUN = _MANIFEST["plan"][int(os.environ["ZOO_RUN"])]
FAILING = frozenset(RUN["failing"])


def pytest_collection_modifyitems(items):
    position = {nodeid: index for index, nodeid in enumerate(RUN["order"])}
    items.sort(key=lambda item: position[item.nodeid])


@pytest.fixture
def planned_failure(request):
    """Whether the plan says this test fails in this run."""
    return request.node.nodeid in FAILING


@pytest.fixture
def zoo_run():
    """This run's entry in the plan."""
    return RUN
'''


def _docstring(summary: str, detail: str = "") -> str:
    lines = [f'"""{summary}', "", "Generated by benchmarks.zoo."]
    if detail:
        lines[-1] += f" {detail}"
    return "\n".join(lines) + '\n"""\n'


def _z1(size: int) -> str:
    victims = "".join(
        f"""

def test_z1_victim_{i}(planned_failure):
    if planned_failure:
        raise AssertionError(f"module cache polluted by an earlier test: {{CACHE!r}}")
"""
        for i in range(1, size + 1)
    )
    return (
        _docstring(
            "Z1, test order and shared state: a polluter leaves a module-level cache dirty.",
            "In runs where the victims fail, the polluter runs first.",
        )
        + """
CACHE = {}


def test_z1_polluter():
    CACHE["session"] = "left behind by test_z1_polluter"
"""
        + victims
    )


def _z2(size: int) -> str:
    members = "".join(
        f"""

def test_z2_wait_{i}(planned_failure, slow_service):
    time.sleep(TIMEOUT if planned_failure else 0.005)
    if planned_failure:
        raise TimeoutError(f"event not set within {{TIMEOUT:.2f}}s")
"""
        for i in range(1, size + 1)
    )
    return (
        _docstring(
            "Z2, async waits: a worker signals completion too late for a tight timeout.",
            "Failing members wait out the whole timeout first.",
        )
        + """
import time

import pytest

TIMEOUT = 0.15


@pytest.fixture(scope="module")
def slow_service():
    time.sleep(0.02)
    return "ready"
"""
        + members
    )


def _z3(size: int) -> str:
    members = "".join(
        f"""

def test_z3_port_{i}(planned_failure):
    if planned_failure:
        raise OSError(98, f"Address already in use: ('127.0.0.1', {{PORT}})")
"""
        for i in range(1, size + 1)
    )
    return (
        _docstring("Z3, resource contention: tests bind the same fixed port.")
        + "\nPORT = 47001\n"
        + members
    )


def _z4(size: int) -> str:
    members = "".join(
        f"""

def test_z4_clock_{i}(planned_failure, zoo_run):
    if planned_failure:
        start = datetime.datetime.fromisoformat(zoo_run["started_at"])
        first = start.date()
        second = (start + datetime.timedelta(seconds=2)).date()
        raise AssertionError(f"date changed between calls: {{second}} != {{first}}")
"""
        for i in range(1, size + 1)
    )
    return (
        _docstring(
            "Z4, time and clock: two clock reads straddle midnight.",
            "Runs that fail these tests start just before midnight UTC (see started_at).",
        )
        + "\nimport datetime\n"
        + members
    )


_Z5_ENDPOINTS = ("health", "orders", "users", "stock", "prices", "carts")


def _z5(size: int) -> str:
    members = []
    for i in range(1, size + 1):
        endpoint = _Z5_ENDPOINTS[(i - 1) % len(_Z5_ENDPOINTS)]
        if i % 2:
            error = (
                f'ConnectionResetError(104, f"Connection reset by peer while reading '
                f'{{SERVICE}}/{endpoint}")'
            )
        else:
            error = f'TimeoutError(f"read timed out after 2.0s from {{SERVICE}}/{endpoint}")'
        members.append(
            f"""

def test_z5_api_{i}(planned_failure):
    if planned_failure:
        raise {error}
"""
        )
    return (
        _docstring("Z5, network: a stub service drops connections and stalls.")
        + '\nSERVICE = "http://stub.zoo.invalid:8080"\n'
        + "".join(members)
    )


def _z6(size: int) -> str:
    members = "".join(
        f"""

def test_z6_order_{i}(planned_failure):
    observed = ["beta", "alpha", "gamma"] if planned_failure else list(EXPECTED)
    assert observed == EXPECTED
"""
        for i in range(1, size + 1)
    )
    return (
        _docstring("Z6, unordered collections: a set's iteration order leaks into an assertion.")
        + '\nEXPECTED = ["alpha", "beta", "gamma"]\n'
        + members
    )


def _z7(size: int) -> str:
    members = "".join(
        f"""

def test_z7_random_{i}(planned_failure):
    values = [] if planned_failure else [3, 1, 2]
    average = sum(values) / len(values)
    assert average > 0
"""
        for i in range(1, size + 1)
    )
    summary = "Z7, unseeded randomness: random input sometimes hits an empty edge case."
    return _docstring(summary) + members


def _controls() -> str:
    passes = "".join(
        f"""

def test_control_pass_{i}():
    assert True
"""
        for i in range(1, CONTROL_PASSES + 1)
    )
    failures = "".join(
        f"""

def test_control_fail_{i}():
    raise AssertionError("control test that always fails")
"""
        for i in range(1, CONTROL_FAILURES + 1)
    )
    summary = "Controls: tests that always pass and tests that always fail."
    return _docstring(summary) + passes + failures


_MODULES: dict[str, Callable[[int], str]] = {
    "Z1": _z1,
    "Z2": _z2,
    "Z3": _z3,
    "Z4": _z4,
    "Z5": _z5,
    "Z6": _z6,
    "Z7": _z7,
}


def suite_files(plan: Plan) -> dict[str, str]:
    """The generated suite as a mapping from file name to exact text."""
    files = {"pytest.ini": PYTEST_INI, "conftest.py": CONFTEST}
    for config in plan.configs:
        files[LAYOUT[config.key].module] = _MODULES[config.key](config.size)
    files[CONTROL_MODULE] = _controls()
    files["manifest.json"] = manifest_json(plan)
    return files


def write_suite(plan: Plan, destination: Path) -> list[Path]:
    """Write the suite into `destination`, creating it if needed, and return the files written."""
    destination.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in suite_files(plan).items():
        path = destination / name
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written
